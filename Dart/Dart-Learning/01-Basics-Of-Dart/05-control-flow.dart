void main()
{
                            // conditional statements:-

   int a=20;
   int b=10;

   if(a>b)
   {
     print("a is greater than b");   //if statement
   }



   if(a>b)
   {
     print("a is greater than b");   
   }
   else
   {
     print("b is greater than a");   //if-else statement
   }



   if(a>b)
   {
     print("a is greater than b");   
   }
   else if(a==b)
   {
     print("a is equal to b");   //if-else if statement
   }
   else
   {
     print("b is greater than a");
   }



   switch(a)
   {
     case 10:
       print("a is equal to 10");
       break;
     case 20:
       print("a is equal to 20");   //switch statement
       break;
     default:
       print("a is not equal to 10 or 20");
   }
             
}